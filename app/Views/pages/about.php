<h1>About the System</h1>

<p>
    The Tasks for Today Management System is a small internal web
    application designed to help a team organize and monitor its daily tasks.
</p>

<p>
    The Welcome page displays only the tasks scheduled for the current date,
    while the complete Task List page displays every task stored in the
    database. The system also includes a demo user profile.
</p>

<p>
    This application was developed using CodeIgniter 4, PHP, MySQL, HTML,
    and CSS. It follows the Model-View-Controller structure to keep database
    operations, application logic, and page presentation properly separated.
</p>

